create table if not exists public.public_site_content (
    id integer primary key check (id = 1),
    payload jsonb not null,
    updated_at timestamptz not null default now()
);

alter table public.public_site_content enable row level security;

revoke all on table public.public_site_content from anon, authenticated;
grant select on table public.public_site_content to anon, authenticated;
grant all on table public.public_site_content to service_role;

drop policy if exists "Public can read public-site content" on public.public_site_content;
create policy "Public can read public-site content"
    on public.public_site_content
    for select
    to anon, authenticated
    using (true);

create table if not exists public.public_concerns (
    id bigint generated by default as identity primary key,
    sender_name text,
    contact text,
    category text not null,
    message text not null,
    status text not null default 'new',
    created_at timestamptz not null default now(),
    constraint public_concerns_category_check
        check (category in ('Certificate or service', 'Resident record', 'Community concern', 'Other')),
    constraint public_concerns_message_check
        check (char_length(btrim(message)) between 10 and 2000),
    constraint public_concerns_sender_name_check
        check (sender_name is null or char_length(sender_name) <= 120),
    constraint public_concerns_contact_check
        check (contact is null or char_length(contact) <= 160),
    constraint public_concerns_status_check
        check (status in ('new', 'reviewed'))
);

alter table public.public_concerns enable row level security;
revoke all on table public.public_concerns from anon, authenticated;
grant insert (sender_name, contact, category, message) on table public.public_concerns to anon, authenticated;
grant usage, select on sequence public.public_concerns_id_seq to anon, authenticated;
grant all on table public.public_concerns to service_role;

drop policy if exists "Public can submit concerns" on public.public_concerns;
create policy "Public can submit concerns"
    on public.public_concerns
    for insert
    to anon, authenticated
    with check (
        status = 'new'
        and category in ('Certificate or service', 'Resident record', 'Community concern', 'Other')
        and char_length(btrim(message)) between 10 and 2000
        and (sender_name is null or char_length(sender_name) <= 120)
        and (contact is null or char_length(contact) <= 160)
    );

create table if not exists public.public_certificate_request_inbox (
    id uuid primary key default gen_random_uuid(),
    requester_name text not null,
    email text,
    contact_number text,
    valid_id_type text,
    valid_id_number text,
    certificate_type text not null,
    purpose text not null,
    status text not null default 'new',
    created_at timestamptz not null default now(),
    constraint public_certificate_request_inbox_name_check
        check (char_length(btrim(requester_name)) between 1 and 120),
    constraint public_certificate_request_inbox_contact_check
        check (
            (email is not null and char_length(btrim(email)) between 1 and 160)
            or (contact_number is not null and char_length(btrim(contact_number)) between 1 and 40)
        ),
    constraint public_certificate_request_inbox_email_check
        check (
            email is null
            or (
                char_length(btrim(email)) <= 160
                and email ~* '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'
            )
        ),
    constraint public_certificate_request_inbox_phone_check
        check (contact_number is null or char_length(btrim(contact_number)) between 1 and 40),
    constraint public_certificate_request_inbox_valid_id_type_check
        check (
            valid_id_type is null
            or valid_id_type in ('PhilSys ID', 'Driver License', 'Passport', 'UMID', 'SSS ID', 'Senior Citizen ID', 'Postal ID', 'PRC ID', 'Other Valid ID')
        ),
    constraint public_certificate_request_inbox_valid_id_number_check
        check (valid_id_number is null or char_length(btrim(valid_id_number)) between 1 and 100),
    constraint public_certificate_request_inbox_type_check
        check (certificate_type in (
            'Barangay Clearance',
            'Certificate of Indigency',
            'Certificate of Residency',
            'Certificate of Good Moral Character',
            'Character Reference',
            'Certificate of Late Registration (Civil Registrar)',
            'Certificate of Death',
            'Permit to Solicit / Ask for Donations',
            'Amicable Settlement',
            'Certificate of Recommendation',
            'Affidavit of Undertaking',
            'Affidavit for Solo Parent',
            'Barangay Business Clearance',
            'Certificate of Solo Parent'
        )),
    constraint public_certificate_request_inbox_purpose_check
        check (char_length(btrim(purpose)) between 10 and 1000),
    constraint public_certificate_request_inbox_status_check
        check (status in ('new', 'imported'))
);

